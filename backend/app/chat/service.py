"""Contextual market assistant grounded in PATRON's numerical output.

PATRON is a forecaster, not a language model. Answers here are generated by
deterministic templates over the live market snapshot, indicators, the rule-based
signal and the latest persisted PATRON forecast. No text model is called and no
forecast value is invented. When data or a model output is unavailable the
responder says so instead of filling the gap.
"""

