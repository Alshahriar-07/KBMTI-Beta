RESPONDER_ID = "patron-grounded-rules-v2"


def _forecast_as_of(latest: dict[str, Any] | None) -> str | None:
    if not isinstance(latest, dict):
        return None
    output = latest.get("output")
    if not isinstance(output, dict):
        return None
    patron = output.get("patron")
    return patron.get("as_of") if isinstance(patron, dict) else None
STAGE_NOTE = (
    "This reply is deterministic text generated from your live market snapshot and the "
    "PATRON forecast JSON. PATRON is a numerical forecaster, not a language model."
)

SUGGESTIONS: list[dict[str, str]] = [
    {"id": "structure", "label": "Market structure", "prompt": "What is the current market structure?"},
    {"id": "why_signal", "label": "Explain the signal", "prompt": "Why is the current signal what it is?"},
    {"id": "forecast", "label": "PATRON forecast", "prompt": "Summarize the latest PATRON forecast."},
    {"id": "barrier", "label": "Barrier probabilities", "prompt": "What do the PATRON barrier probabilities say?"},
    {"id": "invalidation", "label": "Invalidation", "prompt": "What would invalidate the current view?"},
    {"id": "volatility", "label": "Volatility", "prompt": "How volatile is the market right now?"},
    {"id": "timeframes", "label": "Compare timeframes", "prompt": "Which timeframe has clearer conditions?"},
]


class ChatResponder(Protocol):
    responder_id: str

    def respond(self, question: str, context: ChatContext) -> str: ...


@dataclass
class ChatContext:
    symbol: str | None
    timeframe: str
    snapshot: dict[str, Any]
    signal: dict[str, Any]
    candles: list[dict[str, Any]]
    data_state: str
    reason: str | None = None
    extras: dict[str, Any] = field(default_factory=dict)
    patron: dict[str, Any] = field(default_factory=dict)
    latest_forecast: dict[str, Any] | None = None
    history: list[dict[str, str]] = field(default_factory=list)

    @property
    def has_market_data(self) -> bool:
        return bool(self.symbol and self.candles)


def _fmt(value: Any, digits: int = 2) -> str:
    if value is None or isinstance(value, bool):
        return "unavailable"
    try:
        return f"{float(value):,.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def _context_line(context: ChatContext) -> str:
    stamp = context.snapshot.get("candle_time_iso") or context.snapshot.get("last_update") or "unknown time"
    return (
        f"Market context: {context.symbol or 'no symbol'} · {context.timeframe} · "
        f"latest completed candle {stamp} · data {context.data_state}."
    )


class RuleBasedResponder(ChatResponder):
    responder_id = RESPONDER_ID

    def respond(self, question: str, context: ChatContext) -> str:
        text = self._effective_question(question, context)

        # PATRON answers depend on the stored forecast, not on the chart provider,
        # so they are served even when the live feed is disconnected.
        if self._matches(
            text,
            ("forecast", "predict", "prediction", "patron", "barrier", "quantile", "future", "next candle", "next 6"),
        ):
            return self._forecast(context)

        if not context.has_market_data:
            reason = context.reason or "No provider is connected and no cached candles are available."
            return (
                "Market context is unavailable, so I will not invent a market read. "
                f"Reason: {reason}. Connect the Binance feed (or MT5) and select a BTC symbol "
                "to enable contextual answers. A PATRON forecast still requires Binance "
                "BTC/USDT 15m history."
            )
        if self._matches(text, ("invalidat", "weaken", "wrong", "negat", "against")):
            return self._invalidation(context)
        if self._matches(text, ("why", "signal", "bias", "buy", "sell", "wait", "setup")):
            return self._signal(context)
        if self._matches(text, ("volatil", "atr", "range", "spread", "risk")):
            return self._volatility(context)
        if self._matches(text, ("support", "resistance", "level", "swing")):
            return self._levels(context)
        if self._matches(text, ("timeframe", "which chart", "higher time", "compare")):
            return self._timeframes(context)
        if self._matches(text, ("news", "fundamental", "sentiment", "macro", "etf", "halving")):
            return (
                "KBMTI does not ingest news, sentiment or macro feeds. I can describe Binance/MT5 "
                "price data, indicators, the rule-based bias and the latest PATRON forecast JSON, "
                "but I will not invent a news narrative."
            )
        if self._matches(text, ("structure", "trend", "momentum", "market doing")):
            return self._structure(context)
        return self._overview(context)

    @staticmethod
    def _matches(text: str, keywords: tuple[str, ...]) -> bool:
        return any(keyword in text for keyword in keywords)

    @staticmethod
    def _effective_question(question: str, context: ChatContext) -> str:
        """Resolve short follow-ups against the previous user turn (stored context)."""

        text = (question or "").strip().lower()
        follow_ups = {"why", "why?", "explain", "and?", "then?", "what about that", "how so"}
        if text not in follow_ups and len(text) > 18:
            return text
        previous = next(
            (item["content"] for item in reversed(context.history) if item.get("role") == "user"),
            None,
        )
        if not previous:
            return text
        return f"{previous.strip().lower()} {text}".strip()

    # ------------------------------------------------------------------ answers
    def _header(self, context: ChatContext) -> str:
        return (
            f"{context.symbol} on {context.timeframe}. Last completed close "
            f"{_fmt(context.snapshot.get('candle_time') and self._last_close(context))}."
        )

    @staticmethod
    def _last_close(context: ChatContext) -> float | None:
        if not context.candles:
            return None
        return context.candles[-1].get("close")

    def _overview(self, context: ChatContext) -> str:
        signal = context.signal
        return "\n".join(
            [
                f"Here is what the loaded data says for {context.symbol} ({context.timeframe}).",
                f"• Last completed close: {_fmt(self._last_close(context))} · bid {_fmt(context.snapshot.get('bid'))} · ask {_fmt(context.snapshot.get('ask'))} · spread {context.snapshot.get('spread_points') if context.snapshot.get('spread_points') is not None else 'unavailable'} points.",
                f"• Rule-based technical bias: {signal.get('label', 'unavailable')} (score {_fmt(signal.get('score'), 2)}). Engine: {signal.get('engine', 'unknown')}.",
                f"• RSI 14 {_fmt(signal.get('metrics', {}).get('rsi14'), 1)} · MACD histogram {_fmt(signal.get('metrics', {}).get('macd_histogram'), 4)} · ATR 14 {_fmt(signal.get('metrics', {}).get('atr14'), 2)}.",
                "",
                self._patron_line(context),
                "I can explain the signal, summarize the latest PATRON forecast, describe structure and volatility, "
                "list invalidation conditions, or show recent swing levels.",
                "",
                STAGE_NOTE,
                _context_line(context),
            ]
        )

    def _structure(self, context: ChatContext) -> str:
        metrics = context.signal.get("metrics", {})
        close = self._last_close(context)
        ema9, ema21, ema50 = metrics.get("ema9"), metrics.get("ema21"), metrics.get("ema50")
        rsi = metrics.get("rsi14")
        hist = metrics.get("macd_histogram")
        position = "unavailable"
        if close is not None and ema9 is not None and ema21 is not None and ema50 is not None:
            if close > ema9 > ema21 > ema50:
                position = "price above all three EMAs in a bullish stack"
            elif close < ema9 < ema21 < ema50:
                position = "price below all three EMAs in a bearish stack"
            elif close > ema50:
                position = "price above EMA 50 but the short EMAs are not cleanly stacked"
            else:
                position = "price below EMA 50 without a clean bearish stack"
        return "\n".join(
            [
                f"Structure for {context.symbol} {context.timeframe}: {position}.",
                f"• Close {_fmt(close)} · EMA 9 {_fmt(ema9)} · EMA 21 {_fmt(ema21)} · EMA 50 {_fmt(ema50)}.",
                f"• RSI 14 {_fmt(rsi, 1)} · MACD histogram {_fmt(hist, 4)} (line {_fmt(metrics.get('macd'), 4)} vs signal {_fmt(metrics.get('macd_signal'), 4)}).",
                f"• Bollinger bands: {_fmt(metrics.get('bb_lower'))} – {_fmt(metrics.get('bb_middle'))} – {_fmt(metrics.get('bb_upper'))}; ATR 14 {_fmt(metrics.get('atr14'))}.",
                f"• Composite bias: {context.signal.get('label')} with {len(context.signal.get('supporting', []))} supporting and {len(context.signal.get('conflicting', []))} conflicting factors.",
                "",
                STAGE_NOTE,
                _context_line(context),
            ]
        )

    def _signal(self, context: ChatContext) -> str:
        signal = context.signal
        supporting = signal.get("supporting", [])
        conflicting = signal.get("conflicting", [])
        neutral = signal.get("neutral", [])
        warnings = signal.get("warnings", [])
        lines = [
            f"The rule-based bias for {context.symbol} {context.timeframe} is {signal.get('label')} "
            f"(net score {_fmt(signal.get('score'), 2)}).",
        ]
        if supporting:
            lines.append("Supporting evidence:")
            lines.extend(f"• {item['label']}: {item['detail']}" for item in supporting)
        if conflicting:
            lines.append("Conflicting evidence:")
            lines.extend(f"• {item['label']}: {item['detail']}" for item in conflicting)
        if neutral:
            lines.append("Neutral / unaligned:")
            lines.extend(f"• {item['label']}: {item['detail']}" for item in neutral)
        if warnings:
            lines.append("Caveats:")
            lines.extend(f"• {warning}" for warning in warnings)
        lines.extend(
            [
                "",
                "This is a technical rule set, not an order. PATRON's probabilistic forecast is separate "
                "and is summarized on request.",
                _context_line(context),
            ]
        )
        return "\n".join(lines)

    def _invalidation(self, context: ChatContext) -> str:
        invalidation = context.signal.get("invalidation", [])
        metrics = context.signal.get("metrics", {})
        lines = [f"What would weaken or invalidate the current {context.timeframe} view on {context.symbol}:"]
        lines.extend(f"• {item}" for item in invalidation)
        if not invalidation:
            lines.append("• No invalidation conditions are available because the signal could not be computed.")
        lines.extend(
            [
                "",
                f"Concrete references from the snapshot: last close {_fmt(self._last_close(context))}, "
                f"EMA 21 {_fmt(metrics.get('ema21'))}, ATR 14 {_fmt(metrics.get('atr14'))}.",
                STAGE_NOTE,
                _context_line(context),
            ]
        )
        return "\n".join(lines)

    def _volatility(self, context: ChatContext) -> str:
        metrics = context.signal.get("metrics", {})
        atr = metrics.get("atr14")
        close = self._last_close(context)
        spread_points = context.snapshot.get("spread_points")
        band_upper, band_lower = metrics.get("bb_upper"), metrics.get("bb_lower")
        band_width = (band_upper - band_lower) if band_upper is not None and band_lower is not None else None
        atr_percent = (atr / close * 100.0) if atr and close else None
        return "\n".join(
            [
                f"Volatility snapshot for {context.symbol} {context.timeframe}:",
                f"• ATR 14 is {_fmt(atr)} price units"
                + (f" ({_fmt(atr_percent, 3)}% of the last close)." if atr_percent else "."),
                f"• Bollinger band width: {_fmt(band_width)} ({_fmt(band_lower)} to {_fmt(band_upper)}).",
                f"• Current spread: {f'{spread_points} points' if spread_points is not None else 'unavailable'}; "
                f"reported by the broker as bid {_fmt(context.snapshot.get('bid'))} / ask {_fmt(context.snapshot.get('ask'))}.",
                "• Binance real_volume is base-asset volume; MT5 tick_volume is a broker update count and is "
                "not treated as exchange volume.",
                "",
                STAGE_NOTE,
                _context_line(context),
            ]
        )

    def _levels(self, context: ChatContext) -> str:
        window = context.candles[-60:]
        highs = [candle["high"] for candle in window if candle.get("high") is not None]
        lows = [candle["low"] for candle in window if candle.get("low") is not None]
        if not highs or not lows:
            return "Swing levels are unavailable because no completed candles are loaded.\n\n" + _context_line(context)
        last_close = self._last_close(context)
        highest = max(highs)
        lowest = min(lows)
        return "\n".join(
            [
                f"Recent swing extremes from the last {len(window)} completed {context.timeframe} candles:",
                f"• Highest high: {_fmt(highest)} ({(highest - last_close) if last_close else 0:+,.2f} from the last close).",
                f"• Lowest low: {_fmt(lowest)} ({(lowest - last_close) if last_close else 0:+,.2f} from the last close).",
                f"• Last close: {_fmt(last_close)}.",
                "",
                "These are descriptive price levels from the loaded candles, not support/resistance predictions, "
                "entries or targets.",
                STAGE_NOTE,
                _context_line(context),
            ]
        )

    def _timeframes(self, context: ChatContext) -> str:
        return "\n".join(
            [
                f"The workspace is currently set to {context.timeframe} on {context.symbol}.",
                "Cross-timeframe comparison is not calculated from hidden data: KBMTI only analyses the timeframe "
                "you select. Switch the timeframe in the top bar (M1, M5, M15, M30, H1, H4) and the indicators and bias "
                "are recomputed from that series.",
                f"Current {context.timeframe} read: {context.signal.get('label')} (score {_fmt(context.signal.get('score'), 2)}).",
                "",
                STAGE_NOTE,
                _context_line(context),
            ]
        )

    def _patron_line(self, context: ChatContext) -> str:
        patron = context.patron or {}
        if not patron:
            return "• PATRON: status unavailable."
        if patron.get("ready"):
            return (
                f"• PATRON: ready · {patron.get('model_id', 'patron-1.0.0')} · "
                f"{patron.get('trainable_parameters') or 0:,} parameters · CPU · "
                f"last inference {patron.get('last_inference_at') or 'none yet'}."
            )
        return f"• PATRON: {str(patron.get('state', 'unknown')).lower()} — {patron.get('message', 'not ready')}"

    def _forecast(self, context: ChatContext) -> str:
        patron = context.patron or {}
        lines: list[str] = []
        if not patron.get("ready"):
            lines.append("PATRON is not ready, so there is no model forecast to summarize.")
            lines.append(f"State: {patron.get('state', 'unknown')}. {patron.get('message', '')}".strip())
            if patron.get("last_error"):
                lines.append(f"Last error: {patron['last_error']}")
            lines.extend(
                [
                    "",
                    "No forecast value is substituted. Open Forecasts after the checkpoint loads and run a forecast.",
                    STAGE_NOTE,
                    _context_line(context),
                ]
            )
            return "\n".join(lines)

        latest = context.latest_forecast
        if not latest or not latest.get("output"):
            lines.append("PATRON is ready, but no forecast run has been persisted yet.")
            lines.append(
                "Open the Forecasts page and press Run forecast; this answer will then summarize the "
                "actual stored model output."
            )
            if patron.get("last_inference_at"):
                lines.append(
                    f"Last inference: {patron.get('last_inference_at')} · "
                    f"status {patron.get('last_status') or 'unknown'} · "
                    f"{patron.get('last_latency_ms') or '—'} ms."
                )
            lines.extend(["", STAGE_NOTE, _context_line(context)])
            return "\n".join(lines)

        output = latest["output"]
        payload = output.get("patron") if isinstance(output, dict) else None
        if not isinstance(payload, dict):
            payload = output if isinstance(output, dict) else {}
        meta = output.get("meta") if isinstance(output, dict) else None
        meta = meta if isinstance(meta, dict) else {}
        reference = meta.get("reference_close")
        if reference is None and latest.get("candles"):
            reference = latest["candles"][0].get("open")
        reference = float(reference) if reference is not None else self._last_close(context)

        steps = payload.get("range_quantiles") or []
        if not steps or reference is None:
            lines.append("The stored PATRON payload has no usable quantiles; nothing is inferred here.")
            lines.extend(["", STAGE_NOTE, _context_line(context)])
            return "\n".join(lines)

        final = steps[-1]
        median = reference * (1.0 + float(final["close"]["q50"]))
        band_low = reference * (1.0 + float(final["close"]["q10"]))
        band_high = reference * (1.0 + float(final["close"]["q90"]))
        barrier = payload.get("barrier_probabilities") or {}
        momentum = payload.get("momentum") or {}
        momentum_probs = momentum.get("class_probabilities") or {}
        momentum_class = momentum.get("predicted_class") or "unavailable"
        patterns = payload.get("pattern_scores") or {}
        top_patterns = sorted(patterns.items(), key=lambda item: item[1], reverse=True)[:3]

        lines.append(
            f"PATRON {payload.get('model_version', 'patron-1.0.0')} forecast as of "
            f"{payload.get('as_of') or latest.get('created_at')}, run {latest.get('id')}."
        )
        lines.append(
            f"• Horizon: {len(steps)} × 15m candles ({len(steps) * 15} minutes) from the "
            f"reference close {_fmt(reference)}."
        )
        lines.append(
            "• Median close path: "
            + " · ".join(
                f"+{int(step['minutes_ahead'])}m {_fmt(reference * (1.0 + float(step['close']['q50'])))}"
                for step in steps
            )
            + "."
        )
        lines.append(
            f"• Final-step 80% close band: {_fmt(band_low)} – {_fmt(median)} – {_fmt(band_high)} "
            f"(q10 / q50 / q90). The band is conservative and not calibrated."
        )
        if barrier:
            lines.append(
                "• Barrier probabilities: "
                f"take-profit first {_fmt(float(barrier.get('tp_first', 0.0)) * 100.0, 1)}% · "
                f"stop-loss first {_fmt(float(barrier.get('sl_first', 0.0)) * 100.0, 1)}% · "
                f"timeout {_fmt(float(barrier.get('timeout', 0.0)) * 100.0, 1)}% "
                "(TP = +1.5 ATR14, SL = −1.0 ATR14)."
            )
        lines.append(
            f"• Momentum head: {momentum_class} "
            f"({_fmt(float(momentum_probs.get(momentum_class, 0.0)) * 100.0, 1)}%). "
            "This head is close to chance on the reference test split."
        )
        if top_patterns:
            lines.append(
                "• Highest pattern presence: "
                + ", ".join(f"{name} {_fmt(float(score) * 100.0, 1)}%" for name, score in top_patterns)
                + " (uncalibrated multi-label scores)."
            )
        lines.append(
            f"• Runtime: {latest.get('latency_ms') if latest.get('latency_ms') is not None else '—'} ms · "
            f"checkpoint {str(patron.get('checkpoint_path', '—')).split(chr(92))[-1] if patron.get('checkpoint_path') else '—'}."
        )
        if latest.get("warnings"):
            lines.append("• Derivation warnings: " + "; ".join(str(item) for item in latest["warnings"]))
        lines.append(
            "• Reference metrics: barrier accuracy 0.3813 and momentum near chance on PATRON's "
            "held-out test split. Treat this as a probabilistic research estimate, not a signal to trade."
        )
        lines.extend(["", STAGE_NOTE, _context_line(context)])
        return "\n".join(lines)


class ChatService:
    def __init__(
        self,
        repository: ChatRepository,
        market: MarketService,
        signals: SignalService,
        forecast: ForecastService,
        patron: PatronInferenceService,
        responder: ChatResponder | None = None,
    ) -> None:
        self.repository = repository
        self.market = market
        self.signals = signals
        self.forecast = forecast
        self.patron = patron
        self.responder = responder or RuleBasedResponder()
        self._lock = threading.RLock()

    # ------------------------------------------------------------------ context
    def build_context(self, conversation_id: str | None = None) -> ChatContext:
        snapshot = self.market.snapshot()
        signal = self.signals.current()
        series = self.market.candle_series(limit=120)
        latest = None
        try:
            latest = self.forecast.latest()
        except Exception:  # pragma: no cover - a broken forecast row must not break chat
            logger.debug("Could not load the latest forecast for chat context", exc_info=True)
        history: list[dict[str, str]] = []
        if conversation_id:
            try:
                history = [
                    {"role": str(item.get("role")), "content": str(item.get("content"))}
                    for item in self.repository.list_messages(conversation_id, limit=8)
                ]
            except Exception:  # pragma: no cover
                history = []
        return ChatContext(
            symbol=snapshot.get("symbol"),
            timeframe=snapshot.get("timeframe") or self.market.status().get("timeframe") or "M15",
            snapshot=snapshot,
            signal=signal,
            candles=series.get("candles", []),
            data_state=series.get("data_state") or snapshot.get("data_state") or "unavailable",
            reason=series.get("stale_reason") or snapshot.get("stale_reason"),
            extras={"forecast": self.forecast.status()},
            patron=self.patron.status(),
            latest_forecast=latest,
            history=history,
        )

    def suggestions(self) -> dict[str, Any]:
        context = self.build_context()
        return {
            "suggestions": SUGGESTIONS,
            "context_available": context.has_market_data,
            "message": None if context.has_market_data else (context.reason or "Market context unavailable."),
            "patron_ready": bool(context.patron.get("ready")),
        }

    # ------------------------------------------------------------- conversations
    def list_conversations(self) -> dict[str, Any]:
        return {"conversations": self.repository.list_conversations()}

    def create_conversation(self, title: str | None = None) -> dict[str, Any]:
        cleaned = (title or "").strip() or "New conversation"
        return self.repository.create_conversation(cleaned[:120])

    def delete_conversation(self, conversation_id: str) -> dict[str, Any]:
        if not self.repository.get_conversation(conversation_id):
            raise NotFoundError("Conversation not found.")
        self.repository.delete_conversation(conversation_id)
        return {"deleted": True, "conversation_id": conversation_id}

    def messages(self, conversation_id: str) -> dict[str, Any]:
        if not self.repository.get_conversation(conversation_id):
            raise NotFoundError("Conversation not found.")
        context = self.build_context(conversation_id)
        return {
            "conversation_id": conversation_id,
            "messages": self.repository.list_messages(conversation_id),
            "context": self._context_meta(context),
        }

    def clear_messages(self, conversation_id: str) -> dict[str, Any]:
        if not self.repository.get_conversation(conversation_id):
            raise NotFoundError("Conversation not found.")
        self.repository.clear_messages(conversation_id)
        return {"cleared": True, "conversation_id": conversation_id}

    def send_message(self, conversation_id: str, content: str) -> dict[str, Any]:
        if not self.repository.get_conversation(conversation_id):
            raise NotFoundError("Conversation not found.")
        question = (content or "").strip()
        if not question:
            raise ValueError("Message content is required.")
        if len(question) > 2000:
            raise ValueError("Messages are limited to 2000 characters.")

        with self._lock:
            context = self.build_context(conversation_id)
            answer = self.responder.respond(question, context)
            meta = self._context_meta(context)
            user_message = self.repository.add_message(conversation_id, "user", question, meta)
            assistant_message = self.repository.add_message(
                conversation_id,
                "assistant",
                answer,
                {
                    **meta,
                    "responder": getattr(self.responder, "responder_id", "unknown"),
                    "patron_grounded": True,
                },
            )

            conversation = self.repository.get_conversation(conversation_id)
            if conversation and conversation.get("title") in ("New conversation", ""):
                title = re.sub(r"\s+", " ", question).strip()[:60]
                self.repository.rename_conversation(conversation_id, title or "New conversation")

            return {"user_message": user_message, "assistant_message": assistant_message, "context": meta}

    @staticmethod
    def _context_meta(context: ChatContext) -> dict[str, Any]:
        latest = context.latest_forecast or {}
        patron = context.patron or {}
